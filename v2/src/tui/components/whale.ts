const compact: readonly string[] = [
  "                   #,",
  "                   ###",
  "                   ####,",
  "             ,#################,",
  "       ,######################,  ###",
  "      ,#########################,,##,",
  "     ,######''     ''################",
  "   ,#',,##############,            ##",
  "  ,#'                '#######,,   ,,,##'",
  "'                            ''###''",
];

const small: readonly string[] = [
  "              #,",
  "        ,,#########,,",
  "     ,################  ##,",
  "   ,####''    ''############",
  "  ,#' ,,#########,,      '##",
  " '          ''########,,##'",
];

const SIZES: readonly { art: readonly string[]; cols: number }[] = [{ art: reference, cols: 84 }, { art: compact, cols: 44 }, { art: small, cols: 32 }];

export function whaleRows(cols: number, budget: number): string[] {
  const size = SIZES.find(s => budget >= s.art.length && cols >= s.cols);
  if (size === undefined) return [];
  const width = Math.max(...size.art.map(row => row.length));
  return size.art.map(line => line.padEnd(width));
}
